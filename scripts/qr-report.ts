// Generates docs/qr-parser-report.md from the regression corpus.
//   npx tsx scripts/qr-report.ts
// The tables are produced by running the real parser, so the report cannot drift from the code.

import fs from 'node:fs'
import { parseQr, PARSER_VERSION, QR_FORMATS, type QrParseResult } from '../lib/qr/parser'
import { BOX_SAMPLES, CARTON_SAMPLES, URL_WRAPPED, LEGACY_DEV_SAMPLES, MALFORMED } from '../tests/qr/corpus'

// The parser that shipped before 18 Nov 2026 (main branch, lib/qr-parser.ts), kept verbatim
// in logic so the report can show what it got wrong.
function oldParser(raw: string): { valid: boolean; art: string; colour: string; size: string; division: string } {
  const normalized = raw.trim().replace(/^https?:\/\//i, '').replace(/\/$/, '').toUpperCase()
  const fields = normalized.split('-')
  const prefixes = ['FL', 'P', 'S']
  const map: Record<string, string> = { FL: 'Flite EVA', P: 'Flite PU', S: 'Sparx' }
  const f0 = fields[0] ?? ''
  const f1 = fields[1] ?? ''
  const valid = fields.length >= 4 && prefixes.some((p) => f0.includes(p)) && f1.length >= 4 && !!f1.slice(4).replace(/\D/g, '') && parseFloat(fields[3] ?? '0') > 0
  let art = f0, division = 'Bahamas'
  for (const p of [...prefixes].sort((a, b) => b.length - a.length)) {
    const i = f0.indexOf(p)
    if (i !== -1) { art = f0.slice(i); division = map[p]; break }
  }
  const digits = f1.slice(4).replace(/\D/g, '')
  return { valid, art, colour: f1.slice(0, 4), size: digits.length >= 2 ? String(parseInt(digits.slice(-2), 10)) : digits || '0', division }
}

const esc = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|')
const v = (r: QrParseResult, k: keyof QrParseResult['fields']) => (r.fields[k] ? String(r.fields[k]!.value) : '')

const out: string[] = []
const P = (s = '') => out.push(s)

P('# QR parser report')
P()
P(`Generated by \`npm run qr:report\` from the regression corpus in \`tests/qr/corpus.ts\`. Parser version \`${PARSER_VERSION}\`.`)
P()
P('Every table below is produced by running the parser; expected values in the corpus were derived by hand from each label and are checked by `npm test`.')
P()
P('## 1. Formats')
P()
P('| Format id | Kind | Layout |')
P('|---|---|---|')
for (const f of QR_FORMATS) P(`| \`${f.id}\` | ${f.kind} | ${esc(f.description)} |`)
P('| `relaxo.box.a1.unknown-variant` | box | Fallback: an "A1" label whose tail matches no known layout. Known fields are read, the rest kept as unknown; status partial; no duplicate key. |')
P()

P('## 2. Individual-box samples')
P()
P(`${BOX_SAMPLES.length} unique labels. All parse with status \`parsed\` and carry a unique key.`)
P()
P('| # | Raw | Format | Article | Colour | Size | MRP | Mfg | Plant | EAN | Ref (9) | Code (5) | Serial | Old parser |')
P('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
BOX_SAMPLES.forEach((s, i) => {
  const r = parseQr(s.raw)
  const o = oldParser(s.raw)
  const oldNote = !o.valid ? '**rejected**' : (o.art !== s.art || o.size !== s.size || o.colour !== s.colour) ? `**misread** (${o.art}/${o.colour}/${o.size})` : `ok, division "${o.division}"`
  P(`| ${i + 1} | \`${s.raw}\` | ${r.formatId?.replace('relaxo.box.a1.', '')} | ${v(r, 'articleCode')} | ${v(r, 'colourCode')} | ${v(r, 'size')} | ${v(r, 'mrp')} | ${String(v(r, 'mfgMonth')).padStart(2, '0')}/${v(r, 'mfgYear')} | ${v(r, 'plantCode')} | ${v(r, 'ean')} | ${v(r, 'batchRef')} | ${v(r, 'labelCode')} | ${v(r, 'serial')} | ${oldNote} |`)
})
P()

P('## 3. Outer-carton samples')
P()
P(`${CARTON_SAMPLES.length} unique labels (the duplicated SF0204G sample is listed once). All parse as cartons; the box scanner refuses them.`)
P()
P('| # | Raw | Format | Article | Colour | Sizes | Pack | MRP | Date | Plant / code | Serial | Issues |')
P('|---|---|---|---|---|---|---|---|---|---|---|---|')
CARTON_SAMPLES.forEach((s, i) => {
  const r = parseQr(s.raw)
  P(`| ${i + 1} | \`${s.raw}\` | ${r.formatId?.replace('relaxo.carton.', '')} | ${v(r, 'articleCode')} | ${v(r, 'colourCode')} | ${v(r, 'sizeFrom')}–${v(r, 'sizeTo')} | ${v(r, 'packCode')} | ${v(r, 'mrp')} | ${v(r, 'cartonDate')} | ${v(r, 'plantCode') || v(r, 'labelCode')} | ${v(r, 'serial')} | ${esc(r.issues.map((x) => x.code).join(', '))} |`)
})
P()

P('## 4. URL-wrapped samples')
P()
P('Phone camera apps turn the payload into a web address (`https://…/`, lower case). The raw text is stored unchanged; the parser strips the wrapper, upper-cases, and produces the **same duplicate key** as the plain label. Every wrapped sample in the corpus is the same physical label as one of the plain samples, so a wrapped rescan is correctly caught as a duplicate. The old scanner compared raw strings and would have counted these boxes twice.')
P()
P('| Raw (wrapped) | Same key as plain label | Format |')
P('|---|---|---|')
for (const w of URL_WRAPPED) {
  const a = parseQr(w.raw), b = parseQr(w.samePlainLabel)
  P(`| \`${w.raw}\` | ${a.dedupeKey === b.dedupeKey ? 'yes' : '**NO**'} | ${a.formatId} |`)
}
P()

P('## 5. Field confidence')
P()
P('| Field | Where | Confidence | Basis |')
P('|---|---|---|---|')
const seen = new Map<string, string>()
for (const raw of [BOX_SAMPLES[0].raw, BOX_SAMPLES.find((b) => b.format === 'relaxo.box.a1.ean')!.raw, CARTON_SAMPLES[0].raw, CARTON_SAMPLES.find((c) => c.format === 'relaxo.carton.hyphen')!.raw]) {
  const r = parseQr(raw)
  for (const [k, f] of Object.entries(r.fields)) {
    const key = `${k}|${r.kind}|${f!.note ?? ''}`
    if (seen.has(key)) continue
    seen.set(key, '')
    P(`| ${k} | ${r.formatId} | ${f!.confidence} | ${esc(f!.note ?? '')} |`)
  }
}
P()

P('## 6. Carton and box sample groups')
P()
P('For each group the carton and its boxes were compared field by field.')
P()
P('| Group | Article | Colour | MRP | Box sizes in carton range | Plant code equal | Carton date vs box month | Common identifier |')
P('|---|---|---|---|---|---|---|---|')
for (const g of [...new Set(CARTON_SAMPLES.filter((c) => c.group).map((c) => c.group!))]) {
  const c = parseQr(CARTON_SAMPLES.find((x) => x.group === g)!.raw)
  const boxes = BOX_SAMPLES.filter((b) => b.group === g).map((b) => parseQr(b.raw))
  const same = (k: keyof QrParseResult['fields']) => boxes.every((b) => v(b, k) === v(c, k)) ? 'same' : 'differs'
  const inRange = boxes.every((b) => Number(v(b, 'size')) >= Number(v(c, 'sizeFrom')) && Number(v(b, 'size')) <= Number(v(c, 'sizeTo')))
  const plant = c.formatId === 'relaxo.carton.compact' ? (boxes.every((b) => v(b, 'plantCode') === v(c, 'plantCode')) ? 'yes' : 'no') : 'n/a (hyphen format)'
  const cm = v(c, 'cartonDate').slice(0, 7)
  const bm = `${v(boxes[0], 'mfgYear')}-${String(v(boxes[0], 'mfgMonth')).padStart(2, '0')}`
  const shared = boxes.some((b) => b.payload.includes(v(c, 'serial')) || c.payload.includes(v(b, 'serial')) || c.payload.includes(v(b, 'labelCode')))
  P(`| ${g} | ${same('articleCode')} | ${same('colourCode')} | ${same('mrp')} | ${inRange ? 'yes' : 'no'} | ${plant} | ${cm === bm ? 'same month' : `carton ${cm}, boxes ${bm}`} | ${shared ? '**found**' : 'none'} |`)
}
P()
P('**Conclusion:** cartons and boxes share product details only (article, colour, MRP, size within range, and on compact labels the 4-digit code). No serial, code or reference on a carton appears on any box in its group, and vice versa. The labels therefore cannot prove which boxes were inside which carton. The carton module must treat carton contents as *expected* (from the approved assortment), never as verified box-level stock.')
P()

P('## 7. Development-database test labels')
P()
for (const raw of LEGACY_DEV_SAMPLES) {
  const r = parseQr(raw)
  P(`- \`${raw}\` → \`${r.formatId}\`, status **${r.status}**, unique id: ${r.hasUniqueId ? 'yes' : 'no'}. ${esc(r.issues.map((i) => i.message).join(' '))}`)
}
P()
P('These 4-field labels exist only in the development database (10 test scans). They match none of the supplied real labels and carry no box identifier. They are kept, imported as partial scans, and cannot be duplicate-checked.')
P()

P('## 8. Malformed and incomplete input')
P()
P('| Case | Input | Status | Kept fields / unknown | First issue |')
P('|---|---|---|---|---|')
for (const m of MALFORMED) {
  const r = parseQr(m.raw)
  const kept = Object.keys(r.fields).join(', ') || '—'
  const unk = r.unknown.map((u) => u.value).join(' ')
  P(`| ${m.name} | \`${esc(m.raw.trim() || '(blank)')}\` | ${r.status} | ${esc(kept)}${unk ? `; unknown: ${esc(unk)}` : ''} | ${esc(r.issues[r.issues.length - 1]?.message ?? '')} |`)
}
P()

const oldRejected = BOX_SAMPLES.filter((s) => !oldParser(s.raw).valid)
const oldMisread = BOX_SAMPLES.filter((s) => { const o = oldParser(s.raw); return o.valid && (o.art !== s.art || o.size !== s.size || o.colour !== s.colour) })
P('## 9. Differences from the previous parser')
P()
P(`- Old parser rejected ${oldRejected.length} real box label(s): ${oldRejected.map((s) => `\`${s.art}\``).join(', ') || 'none'}. The new parser reads all ${BOX_SAMPLES.length}.`)
P(`- Old parser misread ${oldMisread.length} label(s).`)
P('- Old parser took the division from any F/L/P/S letter anywhere in the first field. The new parser does not assign a division at all; the article master does.')
P('- Old duplicate check compared raw text, so URL-wrapped and plain scans of the same box were two different boxes. The new key is the normalised payload.')
P('- Old parser could not read carton labels at all (they were "invalid"). The new parser recognises both carton layouts, so the box scanner can tell the user it is a carton, and the carton module can reuse the same parser.')
P()

P('## 10. Assumptions that still need confirmation')
P()
P('1. **Carton pack letter** (`A` in every compact sample). Is it an assortment / packing code? If yes, the assortment master may need to be keyed by article + size range + this letter.')
P('2. **Carton date**: packing date or manufacturing date? In 5 of 7 groups it falls in the same month as the box manufacturing month; in 2 it is 2 months later.')
P('3. **4-digit code** (1004, 1005, 1006, 1010, 1011, 1001, 1008) and the matching **R-code** on boxes: plant or unit? Not needed for stock, kept for traceability.')
P('4. **MA0 / MA1 / MA2** on box labels: meaning unknown; kept.')
P('5. **9-digit reference** on EAN-bearing box labels: meaning unknown; kept.')
P('6. **Hyphen-format carton tail**: the split between the 5-character code and the serial is uncertain (CU0025G labels give an 11-digit serial with this split). Duplicate detection uses the whole payload, so this does not affect correctness.')
P('7. **Compact carton article code is 7 characters** in every sample. A longer code would shift the colour code; the carton module must validate the result against the article master before trusting it.')
P('8. **Box serial uniqueness**: confirmed by Shayona for individual boxes. The rising serial across divisions suggests one global label counter; not relied on.')
P()

fs.writeFileSync('docs/qr-parser-report.md', out.join('\n'))
console.log(`Wrote docs/qr-parser-report.md (${out.length} lines). Old parser rejected ${oldRejected.length}, misread ${oldMisread.length} of ${BOX_SAMPLES.length} box labels.`)
